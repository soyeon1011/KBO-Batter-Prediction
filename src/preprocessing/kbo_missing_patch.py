# 🌟 3. 데이터 주입 로직
injury_cols = [col for col in df.columns if col.startswith('부상_')]

for name, date, title, severity, category_col in patch_list:
    # 이름이 포함되어 있고, (날짜가 같거나 김인태처럼 이름만 보거나)
    if date == "None":
        mask = (df['선수'].str.contains(name))
    else:
        mask = (df['선수'].str.contains(name)) & (df['부상시작일'] == date)
    
    if mask.any():
        # 기본 정보 업데이트
        df.loc[mask, '뉴스기사제목'] = title
        df.loc[mask, '심각도점수'] = severity
        
        # 0/1 더미 변수 리셋 후 해당 카테고리만 1로 설정
        df.loc[mask, injury_cols] = 0
        if category_col in df.columns:
            df.loc[mask, category_col] = 1
        
        print(f"✅ {name} ({date if date!='None' else '전체'}) 패치 완료")

# 🌟 4. [보너스] 16명의 누락된 성적 복구용 이름 정제
# '김도영(내야수)' -> '김도영'으로 바꿔서 모델링 때 매칭이 잘 되게 합니다.
